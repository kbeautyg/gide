export const COUNTRY_TO_CITIES_MAP: Record<string, string[]> = Object.entries(CITY_TO_COUNTRY_MAP)
  .reduce((acc, [city, country]) => {
    if (!acc[country]) {
      acc[country] = []
    }
    acc[country].push(city)
    return acc
  }, {} as Record<string, string[]>)

