async def fix_locations():
    if not DATABASE_URL:
        print("⚠️ DATABASE_URL не задан")
        return
    
    engine = create_async_engine(DATABASE_URL, echo=False)
    async_session = sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)
    
    async with async_session() as session:
        # Получаем все туры с их location
        result = await session.execute(
            text("SELECT id, location FROM tours WHERE location IS NOT NULL")
        )
        tours = result.fetchall()
        
        fixed_count = 0
        for tour_id, location in tours:
            if not location or ', ' not in location:
                continue
            
            parts = location.split(', ', 1)
            if len(parts) != 2:
                continue
            
            city = parts[0].strip()
            current_country = parts[1].strip()
            
            # Проверяем правильную страну
            correct_country = CITY_COUNTRY_MAP.get(city)
            if correct_country and correct_country != current_country:
                correct_location = f"{city}, {correct_country}"
                await session.execute(
                    text("UPDATE tours SET location = :new_loc WHERE id = :tour_id"),
                    {"new_loc": correct_location, "tour_id": tour_id}
                )
                print(f"  🔧 Тур #{tour_id}: '{location}' → '{correct_location}'")
                fixed_count += 1
        
        await session.commit()
        print(f"✅ Исправлено {fixed_count} туров с неправильной привязкой город→страна")
    
    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(fix_locations())
