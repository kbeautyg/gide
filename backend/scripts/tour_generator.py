"""
Генератор детальных туров для упрощения создания больших объемов контента
"""

def generate_tour_variations(base_template, variations):
    """Генерирует туры на основе базового шаблона и вариаций"""
    tours = []
    
    for var in variations:
        tour = base_template.copy()
        tour.update(var)
        
        # Генерируем what_to_expect если не указано
        if "what_to_expect" not in tour or not tour["what_to_expect"]:
            tour["what_to_expect"] = generate_what_to_expect(tour)
        
        # Генерируем organizational_details если не указано
        if "organizational_details" not in tour or not tour["organizational_details"]:
            tour["organizational_details"] = generate_org_details(tour)
            
        # Генерируем long_description если не указано
        if "long_description" not in tour or not tour["long_description"]:
            tour["long_description"] = generate_long_description(tour)
            
        tours.append(tour)
    
    return tours


def generate_what_to_expect(tour):
    """Генерирует секцию 'Что вас ожидает'"""
    category = tour.get("category", "Экскурсия")
    location = tour.get("location", "")
    
    points = [
        f"• Встреча в удобном месте в центре города {location}",
        f"• Трансфер на комфортабельном транспорте с кондиционером",
        f"• Посещение главных достопримечательностей по маршруту",
        f"• Профессиональный гид расскажет историю и интересные факты",
        f"• Остановки для фотографий в самых живописных местах",
        f"• Дегустация местной кухни (если предусмотрено программой)",
        f"• Свободное время для самостоятельного осмотра",
        f"• Ответы на все ваши вопросы от гида",
        f"• Рекомендации по другим местам для посещения",
        f"• Возвращение в отель или центр города"
    ]
    
    return "\n".join(points)


