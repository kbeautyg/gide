def apply_category_defaults(tour):
    """Применяет стандартные параметры для категории"""
    category = tour.get("category", "")
    
    if category in CATEGORY_DEFAULTS:
        defaults = CATEGORY_DEFAULTS[category]
        for key, value in defaults.items():
            if key not in tour or not tour[key]:
                tour[key] = value
    
    # Стандартные поля если не указаны
    if "languages" not in tour:
        tour["languages"] = ["Русский"]
    if "max_group_size" not in tour:
        tour["max_group_size"] = 8 if "VIP" not in tour.get("title", "") else 6
    if "min_age" not in tour:
        tour["min_age"] = 0
    if "formats" not in tour:
        tour["formats"] = ["Групповые туры"]
    if "landmarks" not in tour:
        tour["landmarks"] = ["Главные достопримечательности"]
    if "is_public" not in tour:
        tour["is_public"] = True
    if "active" not in tour:
        tour["active"] = True
        
    return tour

